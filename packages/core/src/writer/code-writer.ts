/** Minimal line-oriented emitter, so generators never juggle indentation. */
export class CodeWriter {
  private readonly lines: string[] = [];
  private depth = 0;

  constructor(private readonly indent: string = "  ") {}

  /** Appends one line at the current depth. Empty input emits a blank line. */
  line(text = ""): this {
    this.lines.push(text.length === 0 ? "" : this.indent.repeat(this.depth) + text);

    return this;
  }

  /** Appends several lines at the current depth. */
  linesOf(texts: readonly string[]): this {
    for (const text of texts) {
      this.line(text);
    }

    return this;
  }

  /** Appends a blank line unless the output is empty or already blank. */
  blank(): this {
    const last = this.lines[this.lines.length - 1];

    if (this.lines.length > 0 && last !== "") {
      this.lines.push("");
    }

    return this;
  }

  indented(body: () => void): this {
    this.depth += 1;

    try {
      body();
    } finally {
      this.depth -= 1;
    }

    return this;
  }

  /** Emits `open`, an indented body, then `close`. */
  block(open: string, body: () => void, close: string): this {
    this.line(open);
    this.indented(body);
    this.line(close);

    return this;
  }

  toString(): string {
    return `${this.lines.join("\n").replace(/\n+$/, "")}\n`;
  }
}

/** Prefixes every line of `text` with a comment marker. */
export function commentBlock(text: string, marker = "//"): string {
  return text
    .split("\n")
    .map((line) => (line.length === 0 ? marker : `${marker} ${line}`))
    .join("\n");
}

