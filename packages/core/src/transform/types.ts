import type { TransformationContext } from "../context/index.js";
import type { Diagnostic } from "../diagnostics/index.js";
import type { ObjectNode } from "../ir/index.js";
import type { ApiModel } from "../api/index.js";
import type { RelationalModel } from "../relational/index.js";

/**
 * Which intermediate representation a parser produces and a generator
 * consumes. A parser and a generator can only be paired when these match,
 * which is what stops the engine from feeding a JSON type graph to an ERD
 * generator that needs tables and foreign keys.
 */
export type IrKind = "type-graph" | "relational" | "api";

/** A single emitted artifact. */
export interface GeneratedFile {
  /** Path relative to the chosen output directory, for example `Root.java`. */
  readonly path: string;
  readonly content: string;
}

export interface GenerateResult {
  readonly files: readonly GeneratedFile[];
  /**
   * Single-document rendering for editors and the web UI. For languages that
   * allow several types per file this is identical to the only file.
   */
  readonly preview: string;
  readonly diagnostics?: readonly Diagnostic[];
}

export interface ParseResult {
  readonly root: ObjectNode;
  readonly context: TransformationContext;
  readonly diagnostics: readonly Diagnostic[];
}

export interface RelationalParseResult {
  readonly model: RelationalModel;
  readonly diagnostics: readonly Diagnostic[];
}

export interface ApiParseResult {
  readonly model: ApiModel;
  readonly diagnostics: readonly Diagnostic[];
}

export interface ParseOptions {
  /** Name given to the root type. Defaults to `Root`. */
  readonly rootName?: string;
}

export interface GeneratorOptions {
  /** Java package / Go package / C# namespace / Python module. */
  readonly packageName?: string;
  /** Indentation string. Each generator supplies its idiomatic default. */
  readonly indent?: string;
  /** Emit a "generated by DevBridge" header comment. Defaults to false. */
  readonly header?: boolean;
  /**
   * Target-specific flavour, for example `class` or `record` for Java.
   * Unknown values are rejected by the generator.
   */
  readonly style?: string;
  /** Emit serialization annotations/tags where the target supports them. */
  readonly jsonAnnotations?: boolean;
}

interface FormatMeta {
  /** Stable id used by the CLI and the registry, for example `json`. */
  readonly id: string;
  readonly label: string;
}

/** Turns source text into the type-graph IR. */
export interface SourceParser extends FormatMeta {
  readonly irKind: "type-graph";
  /** File extensions this parser accepts, without the leading dot. */
  readonly extensions: readonly string[];
  parse(input: string, options?: ParseOptions): ParseResult;
  /** Reports problems without throwing. Returns [] when the input is valid. */
  validate(input: string): readonly Diagnostic[];
}

/** Turns source text into the relational IR. */
export interface RelationalSourceParser extends FormatMeta {
  readonly irKind: "relational";
  readonly extensions: readonly string[];
  parse(input: string, options?: ParseOptions): RelationalParseResult;
  validate(input: string): readonly Diagnostic[];
}

/** Turns source text into the API IR. */
export interface ApiSourceParser extends FormatMeta {
  readonly irKind: "api";
  readonly extensions: readonly string[];
  parse(input: string, options?: ParseOptions): ApiParseResult;
  validate(input: string): readonly Diagnostic[];
}

/**
 * Lets a parser offer the type-graph IR *in addition* to its primary one.
 *
 * Most source formats describe one kind of thing, and the `irKind` pairing
 * rule exists because feeding a JSON type graph to an ERD generator is a
 * mistake worth naming. OpenAPI is the real exception: its `paths` are HTTP
 * endpoints and its `components/schemas` are data shapes, and both readings
 * are legitimate — which half you want depends on what you asked for.
 *
 * So rather than forcing one reading, or splitting one format into two source
 * entries the user has to choose between, such a parser declares the extra IR
 * it can produce and the engine picks based on the chosen target.
 *
 * This is deliberately an addition rather than a general "list of IRs" on
 * every parser: only one secondary IR has turned out to be worth having, and
 * it is always the type graph, because that is where the generators are.
 */
export interface AlsoProducesTypeGraph {
  readonly alsoProduces: "type-graph";
  parseTypeGraph(input: string, options?: ParseOptions): ParseResult;
}

export type AnySourceParser =
  | SourceParser
  | RelationalSourceParser
  | ApiSourceParser
  | (RelationalSourceParser & AlsoProducesTypeGraph)
  | (ApiSourceParser & AlsoProducesTypeGraph);

/** True when `parser` can also produce the type-graph IR. */
export function producesTypeGraph(
  parser: AnySourceParser,
): parser is AnySourceParser & AlsoProducesTypeGraph {
  return (
    "alsoProduces" in parser &&
    parser.alsoProduces === "type-graph" &&
    typeof (parser as AlsoProducesTypeGraph).parseTypeGraph === "function"
  );
}

/** Every IR `parser` can produce, primary first. */
export function irKindsOf(parser: AnySourceParser): readonly IrKind[] {
  return producesTypeGraph(parser)
    ? [parser.irKind, "type-graph"]
    : [parser.irKind];
}

/** Turns the type-graph IR into target source code. */
export interface TargetGenerator extends FormatMeta {
  readonly irKind: "type-graph";
  /** Primary file extension, without the leading dot. */
  readonly extension: string;
  /** True when the target emits one file per type. */
  readonly filePerType: boolean;
  generate(
    root: ObjectNode,
    context: TransformationContext,
    options?: GeneratorOptions,
  ): GenerateResult;
}

/** Turns the relational IR into a diagram or schema document. */
export interface RelationalGenerator extends FormatMeta {
  readonly irKind: "relational";
  readonly extension: string;
  readonly filePerType: boolean;
  generate(model: RelationalModel, options?: GeneratorOptions): GenerateResult;
}

/** Turns the API IR into a client collection or similar artifact. */
export interface ApiGenerator extends FormatMeta {
  readonly irKind: "api";
  readonly extension: string;
  readonly filePerType: boolean;
  generate(model: ApiModel, options?: GeneratorOptions): GenerateResult;
}

export type AnyTargetGenerator =
  | TargetGenerator
  | RelationalGenerator
  | ApiGenerator;
