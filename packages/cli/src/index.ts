import { mkdir, readFile, writeFile } from "node:fs/promises";
import { dirname, join, relative, resolve } from "node:path";
import { parseArgs } from "node:util";

import type { Diagnostic, GeneratorOptions } from "@devbridge/core";
import { TransformationError, formatDiagnostic } from "@devbridge/core";
import {
  listSources,
  listTargets,
  sourceForFile,
  transform,
  validate,
} from "@devbridge/engine";

export interface CliIo {
  readonly out: (text: string) => void;
  readonly err: (text: string) => void;
  readonly readStdin: () => Promise<string>;
}

const USAGE = `DevBridge — turn an artifact you have into the one you need next.

Usage:
  devbridge transform <file|-> --to <target> [options]
  devbridge validate  <file|-> [--from <source>]
  devbridge formats
  devbridge --help

Options:
  --to <target>        Target format. Required for transform.
  --from <source>      Source format. Inferred from the file extension.
  --out <dir>          Write generated files into <dir> instead of stdout.
  --root <Name>        Name of the root type. Default: Root.
  --package <name>     Java package, Go package or C# namespace.
  --style <style>      Target specific flavour, e.g. class or record.
  --indent <n|tab>     Indentation width, or "tab".
  --header             Prepend a "generated by DevBridge" comment.
  --no-annotations     Skip serialization annotations/tags.
  --quiet              Suppress informational diagnostics.

Everything runs locally; no input ever leaves the machine.`;

function indentFrom(value: string | undefined): string | undefined {
  if (value === undefined) {
    return undefined;
  }

  if (value === "tab" || value === "\t") {
    return "\t";
  }

  const width = Number.parseInt(value, 10);

  if (Number.isNaN(width) || width < 0 || width > 16) {
    throw new TransformationError(
      `Invalid --indent "${value}". Use a width between 0 and 16, or "tab".`,
    );
  }

  return " ".repeat(width);
}

function reportDiagnostics(
  diagnostics: readonly Diagnostic[],
  io: CliIo,
  quiet: boolean,
): void {
  for (const diagnostic of diagnostics) {
    if (quiet && diagnostic.severity === "info") {
      continue;
    }

    io.err(formatDiagnostic(diagnostic));
  }
}

async function readInput(target: string, io: CliIo): Promise<string> {
  return target === "-" ? io.readStdin() : readFile(target, "utf8");
}

function resolveSource(explicit: string | undefined, file: string): string {
  if (explicit !== undefined) {
    return explicit;
  }

  const inferred = file === "-" ? undefined : sourceForFile(file);

  if (inferred !== undefined) {
    return inferred.id;
  }

  throw new TransformationError(
    `Could not tell the source format of "${file}". Pass --from (${listSources()
      .map((format) => format.id)
      .join(", ")}).`,
  );
}

const OPTIONS = {
  to: { type: "string" },
  from: { type: "string" },
  out: { type: "string" },
  root: { type: "string" },
  package: { type: "string" },
  style: { type: "string" },
  indent: { type: "string" },
  header: { type: "boolean" },
  "no-annotations": { type: "boolean" },
  quiet: { type: "boolean" },
  help: { type: "boolean", short: "h" },
} as const;

function parseCliArgs(argv: readonly string[]) {
  return parseArgs({
    args: [...argv],
    options: OPTIONS,
    allowPositionals: true,
  });
}

/**
 * Runs the CLI. Returns the process exit code instead of exiting, so that the
 * same entry point can be driven from tests.
 */
export async function run(argv: readonly string[], io: CliIo): Promise<number> {
  let parsed: ReturnType<typeof parseCliArgs>;

  try {
    parsed = parseCliArgs(argv);
  } catch (error) {
    io.err(error instanceof Error ? error.message : String(error));
    io.err(USAGE);

    return 2;
  }

  const { values, positionals } = parsed;
  const [command, file] = positionals;

  if (values.help === true || command === undefined) {
    io.out(USAGE);

    return command === undefined && values.help !== true ? 2 : 0;
  }

  try {
    switch (command) {
      case "formats": {
        io.out("Sources:");

        for (const format of listSources()) {
          io.out(`  ${format.id.padEnd(12)}${format.label}`);
        }

        io.out("Targets:");

        for (const format of listTargets()) {
          io.out(`  ${format.id.padEnd(12)}${format.label}`);
        }

        return 0;
      }

      case "validate": {
        if (file === undefined) {
          throw new TransformationError("validate needs a file, or - for stdin.");
        }

        const input = await readInput(file, io);
        const source = resolveSource(values.from, file);
        const diagnostics = validate(input, source);

        reportDiagnostics(diagnostics, io, values.quiet === true);

        if (diagnostics.some((diagnostic) => diagnostic.severity === "error")) {
          return 1;
        }

        io.out(`${file}: valid ${source}`);

        return 0;
      }

      case "transform": {
        if (file === undefined) {
          throw new TransformationError(
            "transform needs a file, or - for stdin.",
          );
        }

        if (values.to === undefined) {
          throw new TransformationError(
            `transform needs --to. Available targets: ${listTargets()
              .map((format) => format.id)
              .join(", ")}.`,
          );
        }

        const input = await readInput(file, io);
        const source = resolveSource(values.from, file);
        const indent = indentFrom(values.indent);

        const generatorOptions: GeneratorOptions = {
          ...(values.package === undefined
            ? {}
            : { packageName: values.package }),
          ...(values.style === undefined ? {} : { style: values.style }),
          ...(indent === undefined ? {} : { indent }),
          ...(values.header === true ? { header: true } : {}),
          ...(values["no-annotations"] === true
            ? { jsonAnnotations: false }
            : {}),
        };

        const result = transform({
          input,
          source,
          target: values.to,
          ...(values.root === undefined
            ? {}
            : { parseOptions: { rootName: values.root } }),
          generatorOptions,
        });

        reportDiagnostics(result.diagnostics, io, values.quiet === true);

        if (values.out === undefined) {
          io.out(result.preview);

          return 0;
        }

        const directory = resolve(values.out);

        await mkdir(directory, { recursive: true });

        for (const generated of result.files) {
          const destination = join(directory, generated.path);

          await mkdir(dirname(destination), { recursive: true });
          await writeFile(destination, generated.content, "utf8");

          io.out(`wrote ${relative(process.cwd(), destination)}`);
        }

        return 0;
      }

      default: {
        io.err(`Unknown command "${command}".`);
        io.err(USAGE);

        return 2;
      }
    }
  } catch (error) {
    if (error instanceof TransformationError) {
      io.err(`error: ${error.message}`);

      for (const diagnostic of error.diagnostics) {
        io.err(`  ${formatDiagnostic(diagnostic)}`);
      }

      return 1;
    }

    io.err(`error: ${error instanceof Error ? error.message : String(error)}`);

    return 1;
  }
}

export { USAGE };
